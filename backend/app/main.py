import os

from fastapi import FastAPI, HTTPException
from fastapi.middleware.cors import CORSMiddleware

from .model_service import (
    DATASET_DESCRIPTION,
    DISCLAIMER,
    MODEL_NAME,
    get_improvement_guidance,
    model_is_ready,
    predict_score,
)
from .schemas import HealthResponse, PredictionRequest, PredictionResponse

app = FastAPI(
    title="Student Performance Prediction API",
    version="0.2.0",
    description="Demo API for estimating student performance with a scikit-learn model.",
)

# Allow the deployed Vercel frontend and local development. Additional origins
# can be supplied as a comma-separated FRONTEND_ORIGINS environment variable.
default_origins = [
    "https://student-performance-prediction-ldj1-jygp8po4c.vercel.app",
    "http://localhost:3000",
]
configured_origins = [
    origin.strip()
    for origin in os.getenv("FRONTEND_ORIGINS", "").split(",")
    if origin.strip()
]
legacy_origin = os.getenv("FRONTEND_ORIGIN", "").strip()
allowed_origins = list(dict.fromkeys(
    default_origins + configured_origins + ([legacy_origin] if legacy_origin else [])
))
app.add_middleware(
    CORSMiddleware,
    allow_origins=allowed_origins,
    # Vercel creates unique preview URLs for deployments; allow those origins too.
    allow_origin_regex=r"https://[a-zA-Z0-9-]+(?:-[a-zA-Z0-9-]+)*\\.vercel\\.app",
    allow_credentials=True,
    allow_methods=["GET", "POST"],
    allow_headers=["Content-Type", "Authorization"],
)


@app.get("/health", response_model=HealthResponse)
def health() -> HealthResponse:
    ready = model_is_ready()
    return HealthResponse(
        status="ok" if ready else "degraded",
        service="student-performance-api",
        model_loaded=ready,
    )


@app.post("/api/predict", response_model=PredictionResponse)
def predict(request: PredictionRequest) -> PredictionResponse:
    features = request.features.model_dump()
    try:
        score = predict_score(features)
    except (FileNotFoundError, ValueError, OSError) as exc:
        raise HTTPException(
            status_code=503,
            detail="The prediction model is unavailable. No prediction was generated.",
        ) from exc

    return PredictionResponse(
        status="ok",
        message="Prediction generated by the demo model.",
        predicted_score=score,
        model_name=MODEL_NAME,
        dataset=DATASET_DESCRIPTION,
        guidance=get_improvement_guidance(features),
        disclaimer=DISCLAIMER,
    )
