import os
import hmac

from fastapi import FastAPI, File, Header, HTTPException, UploadFile
from fastapi.middleware.cors import CORSMiddleware

from .model_service import (
    DATASET_DESCRIPTION,
    DISCLAIMER,
    MODEL_NAME,
    get_improvement_guidance,
    model_is_ready,
    predict_score,
)
from .schemas import HealthResponse, PredictionRequest, PredictionResponse
from .training_service import DatasetValidationError, promote_candidate, train_candidate

app = FastAPI(
    title="Student Performance Prediction API",
    version="0.2.0",
    description="Demo API for estimating student performance with a scikit-learn model.",
)

# Allow the deployed Vercel frontend and local development. Additional origins
# can be supplied as a comma-separated FRONTEND_ORIGINS environment variable.
default_origins = [
    "https://student-performance-prediction-ldj1-jygp8po4c.vercel.app",
    "http://localhost:3000",
]
configured_origins = [
    origin.strip()
    for origin in os.getenv("FRONTEND_ORIGINS", "").split(",")
    if origin.strip()
]
legacy_origin = os.getenv("FRONTEND_ORIGIN", "").strip()
allowed_origins = list(dict.fromkeys(
    default_origins + configured_origins + ([legacy_origin] if legacy_origin else [])
))
app.add_middleware(
    CORSMiddleware,
    allow_origins=allowed_origins,
    # Vercel creates unique preview URLs for deployments; allow those origins too.
    allow_origin_regex=r"https://[a-zA-Z0-9-]+(?:-[a-zA-Z0-9-]+)*\.vercel\.app",
    allow_credentials=True,
    allow_methods=["GET", "POST"],
    allow_headers=["Content-Type", "Authorization", "X-Training-Token"],
)


@app.get("/health", response_model=HealthResponse)
def health() -> HealthResponse:
    ready = model_is_ready()
    return HealthResponse(
        status="ok" if ready else "degraded",
        service="student-performance-api",
        model_loaded=ready,
    )


@app.post("/api/predict", response_model=PredictionResponse)
def predict(request: PredictionRequest) -> PredictionResponse:
    features = request.features.model_dump()
    try:
        score = predict_score(features)
    except (FileNotFoundError, ValueError, OSError) as exc:
        raise HTTPException(
            status_code=503,
            detail="The prediction model is unavailable. No prediction was generated.",
        ) from exc

    return PredictionResponse(
        status="ok",
        message="Prediction generated by the demo model.",
        predicted_score=score,
        model_name=MODEL_NAME,
        dataset=DATASET_DESCRIPTION,
        guidance=get_improvement_guidance(features),
        disclaimer=DISCLAIMER,
    )



def _require_training_token(token: str | None) -> None:
    expected = os.getenv("TRAINING_API_TOKEN", "")
    if not expected:
        raise HTTPException(status_code=503, detail="Model training is disabled until TRAINING_API_TOKEN is configured.")
    if not token or not hmac.compare_digest(token, expected):
        raise HTTPException(status_code=401, detail="A valid training token is required.")


@app.post("/api/train")
async def train_model(file: UploadFile = File(...), x_training_token: str | None = Header(default=None, alias="X-Training-Token")) -> dict:
    """Train a candidate model from an explicitly uploaded CSV; never auto-promote."""
    _require_training_token(x_training_token)
    if not file.filename or not file.filename.lower().endswith(".csv"):
        raise HTTPException(status_code=415, detail="Upload a .csv file.")
    content = await file.read(12 * 1024 * 1024 + 1)
    if len(content) > 12 * 1024 * 1024:
        raise HTTPException(status_code=413, detail="CSV uploads are limited to 12 MiB.")
    try:
        return train_candidate(content)
    except DatasetValidationError as exc:
        raise HTTPException(status_code=422, detail=str(exc)) from exc
    except (OSError, ValueError) as exc:
        raise HTTPException(status_code=400, detail="Training failed while processing the supplied dataset.") from exc


@app.post("/api/train/{candidate_id}/promote")
def promote_model(candidate_id: str, x_training_token: str | None = Header(default=None, alias="X-Training-Token")) -> dict:
    """Promote a candidate only when durable active-model storage is configured."""
    _require_training_token(x_training_token)
    try:
        path = promote_candidate(candidate_id)
    except DatasetValidationError as exc:
        raise HTTPException(status_code=422, detail=str(exc)) from exc
    except FileNotFoundError as exc:
        raise HTTPException(status_code=404, detail=str(exc)) from exc
    except RuntimeError as exc:
        raise HTTPException(status_code=503, detail=str(exc)) from exc
    except OSError as exc:
        raise HTTPException(status_code=500, detail="Could not save the active model artifact.") from exc
    # Clear process cache so the next prediction loads the promoted artifact.
    from .model_service import _load_trained_model
    _load_trained_model.cache_clear()
    return {"status": "ok", "message": "Candidate promoted. The active model cache was cleared.", "active_model_path": path}



