import os

from fastapi import FastAPI, HTTPException
from fastapi.middleware.cors import CORSMiddleware

from .model_service import (
    DATASET_DESCRIPTION,
    DISCLAIMER,
    MODEL_NAME,
    get_improvement_guidance,
    model_is_ready,
    predict_score,
)
from .schemas import HealthResponse, PredictionRequest, PredictionResponse

app = FastAPI(
    title="Student Performance Prediction API",
    version="0.2.0",
    description="Demo API for estimating student performance with a scikit-learn model.",
)

# Set FRONTEND_ORIGIN to the deployed frontend origin before deployment.
allowed_origin = os.getenv("FRONTEND_ORIGIN", "http://localhost:3000")
app.add_middleware(
    CORSMiddleware,
    allow_origins=[allowed_origin],
    allow_credentials=True,
    allow_methods=["GET", "POST"],
    allow_headers=["Content-Type", "Authorization"],
)


@app.get("/health", response_model=HealthResponse)
def health() -> HealthResponse:
    ready = model_is_ready()
    return HealthResponse(
        status="ok" if ready else "degraded",
        service="student-performance-api",
        model_loaded=ready,
    )


@app.post("/api/predict", response_model=PredictionResponse)
def predict(request: PredictionRequest) -> PredictionResponse:
    features = request.features.model_dump()
    try:
        score = predict_score(features)
    except (FileNotFoundError, ValueError, OSError) as exc:
        raise HTTPException(
            status_code=503,
            detail="The prediction model is unavailable. No prediction was generated.",
        ) from exc

    return PredictionResponse(
        status="ok",
        message="Prediction generated by the demo model.",
        predicted_score=score,
        model_name=MODEL_NAME,
        dataset=DATASET_DESCRIPTION,
        guidance=get_improvement_guidance(features),
        disclaimer=DISCLAIMER,
    )
